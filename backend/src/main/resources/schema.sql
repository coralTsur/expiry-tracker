CREATE TABLE items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(20) NOT NULL,
    name VARCHAR(255) NOT NULL,
    expiration_date DATE NOT NULL,
    amount NUMERIC(10, 2),
    current_amount NUMERIC(10, 2),
    last_four_digits VARCHAR(4),
    accepted_stores VARCHAR(1000),
    reminder_enabled BOOLEAN NOT NULL,
    days_before_reminder INTEGER DEFAULT 30,
    redeemed BOOLEAN NOT NULL DEFAULT FALSE,
    CHECK (current_amount <= amount),
    CHECK (CHAR_LENGTH(last_four_digits) = 4),
    CHECK (reminder_enabled = FALSE OR days_before_reminder IS NOT NULL)
);
